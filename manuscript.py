"""Bind phase-change manuscript tables and PDF to versioned experiment evidence.

Uses only the standard library until PDF verification needs pypdf. Generating
tables never blesses stale numerical sources; rerun experiments after a change.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent
REPORTS = tuple(f"results/enthalpy-{n}.json" for n in ("baseline", "comparison", "refinement"))
GENERATED = tuple(f"results/paper-{n}.tex" for n in ("uniform", "slab", "heat", "front", "numbers"))


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load_evidence(root=ROOT):
    reports = [json.loads((root / p).read_text(encoding="utf-8")) for p in REPORTS]
    for name, data in zip(REPORTS, reports):
        hashes = data["source_sha256"]
        if not hashes:
            raise ValueError(f"Missing source evidence: {name}")
        for path, expected in hashes.items():
            target = (root / path).resolve()
            if not target.is_relative_to(root.resolve()) or digest(target) != expected:
                raise ValueError(f"Stale numerical source in {name}: {path}")
    baseline, comparison, refinement = reports
    required = {p.relative_to(root).as_posix() for pattern in
                ("phasechange/*.py", "phasechange/*.json", "native/*")
                for p in root.glob(pattern) if p.is_file()}
    if set(refinement["source_sha256"]) != required:
        raise ValueError("Incomplete refinement source inventory")
    if baseline["max_scaled_temperature_error"] > 1e-12 or baseline["max_scaled_energy_defect"] > 1e-12:
        raise ValueError("Uniform baseline gate failed")
    gates = {"heat_temporal_order", "heat_spatial_order", "heat_algebraic",
             "refined_stefan_front", "conservative_cumulative_energy"}
    if set(refinement["acceptance"]) != gates or not all(v is True for v in refinement["acceptance"].values()):
        raise ValueError("Refinement acceptance evidence failed or missing")
    times = refinement["protocol"]["observation_times_s"]
    for row in refinement["cases"].values():
        for method in ("enthalpy", "frozen"):
            samples = row[method]["samples"]
            if [s["time_s"] for s in samples] != times:
                raise ValueError("Incomplete front observation window")
            if any(s["relative_front_error"] is None or not math.isfinite(s["relative_front_error"])
                   or s["relative_front_error"] < 0 for s in samples):
                raise ValueError("Unresolved or invalid front error")
    return reports


def table(columns, heading, rows):
    return "\n".join([r"% Generated by manuscript.py; do not edit.",
                      r"\begin{center}\small", r"\begin{tabular}{" + columns + r"}\toprule",
                      heading + r"\\\midrule", *[" & ".join(row) + r"\\" for row in rows],
                      r"\bottomrule\end{tabular}\end{center}", ""])


def render_tables(root=ROOT):
    baseline, comparison, refinement = load_evidence(root)
    uniform = []
    for row in comparison["uniform"]:
        if row["subdivisions"] != 1:
            continue
        a, b = (row["methods"][m] for m in ("enthalpy", "frozen"))
        label = row["case"].replace("_", " ")
        uniform.append([label, f'{a["max_temperature_error_K"]:.2e}',
                        f'{b["max_temperature_error_K"]:.2e}',
                        f'{b["max_scaled_cumulative_energy_defect"]:.3e}',
                        f'{abs(b["samples"][-1]["cumulative_defect_J"])/baseline["enthalpy_scale_J_m3"]:.3e}'])
    slab = []
    for row in comparison["heat_cool_slab"]:
        a, b = (row["methods"][m] for m in ("enthalpy", "frozen"))
        slab.append([str(row["subdivisions"]), f'{row["max_sampled_method_difference_K"]:.3f}',
                     f'{a["max_scaled_cumulative_energy_defect"]:.3e}',
                     f'{b["max_scaled_cumulative_energy_defect"]:.3e}'])
    heat = []
    for a, b in zip(refinement["heat"]["temporal"], refinement["heat"]["spatial"]):
        heat.append([str(a["steps"]), f'{a["error_K"]:.4e}', f'{a["order"]:.4f}' if "order" in a else "--",
                     str(b["cells"]), f'{b["error_K"]:.4e}', f'{b["order"]:.4f}' if "order" in b else "--"])
    front = []
    for name, row in refinement["cases"].items():
        a = row["enthalpy"]
        errors = [100*max(s["relative_front_error"] for s in row[m]["samples"]) for m in ("enthalpy", "frozen")]
        front.append([name, str(a["cells"]), f'{a["dt_s"]:g}', f'{a["width_K"]:g}',
                      *[f"{v:.6f}" for v in errors]])
    numbers = {}
    for method, prefix in (("enthalpy", "Conservative"), ("frozen", "Frozen")):
        numbers[prefix + "Front"] = f'{100*max(s["relative_front_error"] for s in refinement["cases"]["refined"][method]["samples"]):.6f}'
        numbers[prefix + "Energy"] = f'{max(c[method]["max_scaled_cumulative_energy_defect"] for c in refinement["cases"].values()):.3e}'
    numbers["MaxResidual"] = f'{max(c[m]["max_scaled_equation_residual"] for c in refinement["cases"].values() for m in ("enthalpy", "frozen")):.3e}'
    numbers["Similarity"] = f'{refinement["similarity_parameter"]:.10f}'
    numbers["HeatAlgebraic"] = f'{max(r["algebraic_error_K"] for r in refinement["heat"]["temporal"]):.3e}'
    numbers["BaselineTemperature"] = f'{baseline["max_scaled_temperature_error"]:.3e}'
    numbers["BaselineEnergy"] = f'{baseline["max_scaled_energy_defect"]:.3e}'
    # Evidence for the deliberately retained unfavorable comparisons.
    for method, prefix in (("enthalpy", "Conservative"), ("frozen", "Frozen")):
        numbers[prefix+"MeshOneEarly"] = f'{100*refinement["cases"]["mesh-1"][method]["samples"][0]["relative_front_error"]:.6f}'
    numbers["CoarseTimeEarly"] = f'{100*refinement["cases"]["time-0"]["enthalpy"]["samples"][0]["relative_front_error"]:.6f}'
    numbers["FineTimeEarly"] = f'{100*refinement["cases"]["refined"]["enthalpy"]["samples"][0]["relative_front_error"]:.6f}'
    return dict(zip(GENERATED, [
        table("lrrrr", r"One step per segment & $E_T^H$ (K) & $E_T^F$ (K) & $D^F_{\max}$ & $D^F_{\rm end}$", uniform),
        table("rrrr", r"Subdivisions & $\max|T_H-T_F|$ (K) & $D^H_{\max}$ & $D^F_{\max}$", slab),
        table("rrrrrr", r"Steps & Time error (K) & Order & Cells & Space error (K) & Order", heat),
        table("lrrrrr", r"Setting & Cells & $\Delta t$ (s) & $w$ (K) & $E_s^H$ (\%) & $E_s^F$ (\%)", front),
        "% Generated by manuscript.py; do not edit.\n" + "".join(
            "\\newcommand{\\"+key+"}{"+value+"}\n" for key, value in numbers.items())]))


def check_tables(root=ROOT):
    for path, expected in render_tables(root).items():
        if (root / path).read_text(encoding="utf-8") != expected:
            raise ValueError(f"Stale manuscript table: {path}")


def input_paths(root=ROOT):
    reports = load_evidence(root)
    paths = {"paper/paper.tex", "paper/paper.pdf", "manuscript.py", "suite.py", "suite.json",
             ".github/workflows/validate.yml", "tests/test_manuscript.py", *REPORTS, *GENERATED}
    for report in reports:
        paths.update(report["source_sha256"])
    return sorted(paths)


def check_report(root=ROOT):
    from pypdf import PdfReader
    check_tables(root)
    data = json.loads((root / "paper/build-report.json").read_text(encoding="utf-8"))
    if set(data["sha256"]) != set(input_paths(root)):
        raise ValueError("Incomplete manuscript input inventory")
    for path, expected in data["sha256"].items():
        if digest(root / path) != expected:
            raise ValueError(f"Stale manuscript build: {path}")
    pages = len(PdfReader(root / "paper/paper.pdf").pages)
    if not 1 <= pages <= 5 or data["pages"] != pages:
        raise ValueError("Manuscript page-count mismatch or limit exceeded")
    return pages


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("generate", "check", "check-report"))
    args = parser.parse_args()
    if args.command == "generate":
        for path, content in render_tables().items():
            (ROOT / path).write_text(content, encoding="utf-8", newline="\n")
    elif args.command == "check":
        check_tables()
    else:
        print(f"Verified all inputs and {check_report()} manuscript pages.")
